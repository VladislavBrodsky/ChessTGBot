MAINNET_GLOBAL_ID = -239
AUTH_SIGNED_EXTERNAL = 0x7369676E
OUT_ACTION_SEND_MSG = 0x0EC3C86D
SEND_MODE_PAY_GAS_SEPARATELY = 1
SEND_MODE_IGNORE_ERRORS = 2
CELL_BITS = 1023
CELL_REFS = 4


def wallet_id(network_global_id: int = MAINNET_GLOBAL_ID, workchain: int = 0, subwallet: int = 0) -> int:
    """Client-context wallet id: (1 | int8 wc | uint8 version=0 | uint15 subwallet) xor network id."""
    context = (1 << 31) | ((workchain & 0xFF) << 23) | (0 << 15) | (subwallet & 0x7FFF)
    if context >= 1 << 31:
        context -= 1 << 32  # the reference reads it back as a signed int32
    value = network_global_id ^ context
    if not -(1 << 31) <= value < (1 << 31):
        raise ValueError("wallet id out of int32 range")
    return value


def _used_bits(cell: Cell) -> int:
    return cell.bits.get_used_bits()


def _append(dst: Cell, src: Cell) -> None:
    """storeBuilder / storeSlice: copy src's bits and refs into dst."""
    dst.bits.write_bit_string(src.bits)
    dst.refs.extend(src.refs)


class WalletV5R1:
    def __init__(self, public_key: bytes, secret_key: bytes, workchain: int = 0):
        if len(public_key) != 32 or len(secret_key) != 64:
            raise ValueError("W5 needs a 32-byte public key and a 64-byte ed25519 secret key")
        self.public_key = bytes(public_key)
        self.secret_key = bytes(secret_key)
        self.workchain = workchain
        self.wallet_id = wallet_id(workchain=workchain)

        data = Cell()
        data.bits.write_uint(1, 1)  # signature auth allowed
        data.bits.write_uint(0, 32)  # seqno
        data.bits.write_int(self.wallet_id, 32)
        data.bits.write_bytes(self.public_key)
        data.bits.write_bit(0)  # empty extensions dict
        self.data = data

        state_init = Cell()
        state_init.bits.write_bit(0)  # no split_depth
        state_init.bits.write_bit(0)  # not special
        state_init.bits.write_bit(1)
        state_init.refs.append(W5R1_CODE)
        state_init.bits.write_bit(1)
        state_init.refs.append(data)
        state_init.bits.write_bit(0)  # no libraries
        self.state_init = state_init

        self.address = Address(f"{workchain}:{state_init.bytes_hash().hex()}")

    # -- message parts -------------------------------------------------------

    @staticmethod
    def internal_message(dest: Address, value_nanoton: int, body: Optional[Cell], bounce: bool) -> Cell:
        """storeMessageRelaxed(internal({...})) with @ton/core's inline-vs-ref rule for the body."""
        msg = Cell()
        msg.bits.write_bit(0)  # int_msg_info$0
        msg.bits.write_bit(1)  # ihr_disabled
        msg.bits.write_bit(1 if bounce else 0)
        msg.bits.write_bit(0)  # bounced
        msg.bits.write_address(None)  # src: addr_none
        msg.bits.write_address(dest)
        msg.bits.write_grams(value_nanoton)
        msg.bits.write_bit(0)  # no extra currencies
        msg.bits.write_grams(0)  # ihr_fee
        msg.bits.write_grams(0)  # fwd_fee
        msg.bits.write_uint(0, 64)  # created_lt
        msg.bits.write_uint(0, 32)  # created_at
        msg.bits.write_bit(0)  # no state init
        body = body if body is not None else Cell()
        available = CELL_BITS - _used_bits(msg)
        if available - 1 >= _used_bits(body) and len(msg.refs) + len(body.refs) <= CELL_REFS:
            msg.bits.write_bit(0)
            _append(msg, body)
        else:
            msg.bits.write_bit(1)
            msg.refs.append(body)
        return msg

    def signed_request(self, seqno: int, valid_until: int, out_msg: Cell, send_mode: int) -> Cell:
        """createWalletTransferV5R1 for one sendMsg action, signature at the tail."""
        mode = send_mode | SEND_MODE_IGNORE_ERRORS  # toSafeV5R1SendMode for external auth
        # storeOutList([action]): cell(ref(empty), tag, mode, ref(msg))
        out_list = Cell()
        out_list.refs.append(Cell())
        out_list.bits.write_uint(OUT_ACTION_SEND_MSG, 32)
        out_list.bits.write_uint(mode, 8)
        out_list.refs.append(out_msg)

        signing = Cell()
        signing.bits.write_uint(AUTH_SIGNED_EXTERNAL, 32)
        signing.bits.write_int(self.wallet_id, 32)
        if seqno == 0:
            signing.bits.write_uint(0xFFFFFFFF, 32)
        else:
            signing.bits.write_uint(valid_until, 32)
        signing.bits.write_uint(seqno, 32)
        signing.bits.write_bit(1)  # Maybe ^OutList
        signing.refs.append(out_list)
        signing.bits.write_bit(0)  # no extended actions

        signature = sign_message(bytes(signing.bytes_hash()), self.secret_key).signature
        body = Cell()
        _append(body, signing)
        body.bits.write_bytes(signature)
        return body

    def external_message(self, body: Cell, include_state_init: bool) -> Cell:
        """storeMessage(external({to: self, init?, body})) with @ton/core's ref rules."""
        msg = Cell()
        msg.bits.write_uint(2, 2)  # ext_in_msg_info$10
        msg.bits.write_address(None)
        msg.bits.write_address(self.address)
        msg.bits.write_grams(0)  # import_fee
        if include_state_init:
            msg.bits.write_bit(1)
            available = CELL_BITS - _used_bits(msg)
            if available - 2 < _used_bits(self.state_init) + _used_bits(body):
                msg.bits.write_bit(1)
                msg.refs.append(self.state_init)
            else:
                msg.bits.write_bit(0)
                _append(msg, self.state_init)
        else:
            msg.bits.write_bit(0)
        available = CELL_BITS - _used_bits(msg)
        if available - 1 < _used_bits(body) or len(msg.refs) + len(body.refs) > CELL_REFS:
            msg.bits.write_bit(1)
            msg.refs.append(body)
        else:
            msg.bits.write_bit(0)
            _append(msg, body)
        return msg

    def create_transfer_message(
        self,
        *,
        to_addr: str,
        amount: int,
        seqno: int,
        valid_until: int,
        payload: Optional[Cell] = None,
        bounce: Optional[bool] = None,
        send_mode: int = SEND_MODE_PAY_GAS_SEPARATELY | SEND_MODE_IGNORE_ERRORS,
    ) -> Cell:
        dest = Address(to_addr)
        out_msg = self.internal_message(dest, amount, payload, dest.is_bounceable if bounce is None else bounce)
        body = self.signed_request(seqno, valid_until, out_msg, send_mode)
        return self.external_message(body, include_state_init=seqno == 0)

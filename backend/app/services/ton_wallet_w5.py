"""Wallet V5R1 ("W5", Tonkeeper's default) signing on top of tonsdk cells.

tonsdk only ships wallets up to v4r2, so a Tonkeeper wallet shows the owner a
W5 address while tonsdk would derive a different v4r2 address from the same
seed. This module reproduces the reference implementation in @ton/ton
(WalletContractV5R1 + createWalletTransferV5R1) and @ton/core
(storeMessage / storeMessageRelaxed / storeOutList) closely enough that the
external message is byte-identical; tests/test_ton_wallet_w5.py pins that
against vectors generated by @ton/ton.

Only what payouts need is implemented: one outgoing internal message per
signed external request, mainnet wallet id, subwallet 0, no extensions.
"""


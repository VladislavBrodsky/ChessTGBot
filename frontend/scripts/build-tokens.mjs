// Generates src/styles/tokens.css from design-system/app/tokens.json.
// Run: npm run tokens          (writes the file)
//      npm run tokens -- --check   (CI: fails when the committed file is stale)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../design-system/app/tokens.json');
const target = resolve(here, '../src/styles/tokens.css');
const tokens = JSON.parse(readFileSync(source, 'utf8'));
const entries = (group) => Object.entries(tokens[group]).filter(([key]) => !key.startsWith('$'));

const lines = [
  '/* GENERATED by scripts/build-tokens.mjs from design-system/app/tokens.json. Do not edit by hand. */',
  ':root {',
];
for (const [name, t] of entries('type')) {
  lines.push(`  --type-${name}-size: ${t.size};`, `  --type-${name}-leading: ${t.leading};`, `  --type-${name}-weight: ${t.weight};`, `  --type-${name}-tracking: ${t.tracking};`);
}
for (const group of ['space', 'size', 'radius', 'z', 'motion']) {
  for (const [name, value] of entries(group)) lines.push(`  --${group === 'z' ? 'z' : group}-${name}: ${value};`);
}
lines.push('}', '');

// Role utilities: one class sets the whole role, so size/leading/weight/tracking can never drift apart.
lines.push('@layer components {');
for (const [name, t] of entries('type')) {
  const numeric = name.startsWith('numeric');
  lines.push(`  .t-${name} { font-size: var(--type-${name}-size); line-height: var(--type-${name}-leading); font-weight: var(--type-${name}-weight); letter-spacing: var(--type-${name}-tracking);${numeric ? ' font-variant-numeric: tabular-nums;' : ''}${name === 'eyebrow' ? ' text-transform: uppercase;' : ''} }`);
}
lines.push('  :lang(ar) .t-eyebrow, :lang(hi) .t-eyebrow, :lang(ja) .t-eyebrow, :lang(zh) .t-eyebrow { letter-spacing: 0; text-transform: none; }');
lines.push('}', '');

// Size utilities for Tailwind-style composition (h-control-md, size-tile-lg, ...).
lines.push('@utility h-control-sm { height: var(--size-control-sm); }', '@utility h-control-md { height: var(--size-control-md); }', '@utility h-control-lg { height: var(--size-control-lg); }');
lines.push('@utility min-h-control-sm { min-height: var(--size-control-sm); }', '@utility min-h-control-md { min-height: var(--size-control-md); }', '@utility min-h-row { min-height: var(--size-row-min); }');
for (const [name] of entries('radius')) if (['chip', 'control', 'tile', 'row', 'card', 'hero', 'sheet'].includes(name)) lines.push(`@utility rounded-${name} { border-radius: var(--radius-${name}); }`);
for (const [name] of entries('size')) if (/^(tile|avatar|icon)-/.test(name)) lines.push(`@utility size-${name} { width: var(--size-${name}); height: var(--size-${name}); }`);
lines.push('');

const css = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== css) { console.error('tokens.css is stale. Run `npm run tokens` in frontend/ and commit the result.'); process.exit(1); }
  console.log('tokens.css is current.');
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${target}`);
}

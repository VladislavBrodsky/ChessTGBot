import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const data = async (path, mime) => `data:${mime};base64,${(await readFile(resolve(root, path))).toString('base64')}`;
const source = JSON.parse(await readFile(resolve(root, 'design-system/website/tokens.json'), 'utf8'));
const names = { ink: 'carbon-black', paper: 'paper-white', canvas: 'warm-canvas', mist: 'mist-gray', line: 'ash', muted: 'slate', smoke: 'smoke', mint: 'mint-chip', voltage: 'voltage-yellow' };
const colors = Object.fromEntries(Object.entries(names).map(([key, token]) => [key, source.color[token].$value]));
const icons = {};
for (const name of ['arrow-up-right', 'arrow-right', 'telegram-logo', 'users-three', 'clock', 'graduation-cap', 'strategy', 'scales', 'check', 'target', 'book-open-text', 'share-network', 'cpu', 'shield-check', 'chats-circle']) {
  icons[name] = await readFile(resolve(root, `website/src/icons/svg/${name}.svg`), 'utf8');
}
const art = {};
for (const name of ['sculpture', 'clock', 'academy', 'stakes', 'fair-play']) art[name] = await data(`website/public/illustrations/chess-${name}.webp`, 'image/webp');
const logoSource = await readFile(resolve(root, 'website/public/brand/w3chess-logo.svg'), 'utf8');
const logoViewBox = logoSource.match(/viewBox="([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+)"/);
if (!logoViewBox) throw Error('The current website logo needs a viewBox for proportional rendering.');
const assets = {
  colors, icons, art,
  mark: await data('website/public/brand/w3chess-symbol.svg', 'image/svg+xml'),
  logos: { light: await data('website/public/brand/w3chess-logo.svg', 'image/svg+xml'), dark: await data('website/public/brand/w3chess-logo-inverse.svg', 'image/svg+xml') },
  logoAspect: Number(logoViewBox[3]) / Number(logoViewBox[4]),
  fonts: { display: await data('website/public/fonts/barlow-condensed-bold.ttf', 'font/ttf'), body: await data('website/public/fonts/onest.ttf', 'font/ttf') },
  provenance: { palette: 'design-system/website/tokens.json', iconPack: 'Phosphor regular / website/src/icons/svg', artwork: 'website/public/illustrations', fonts: 'Barlow Condensed Bold + Onest / website/public/fonts' },
};
await writeFile(resolve(here, 'assets.js'), `// Generated by build-assets.mjs from the existing brand assets.\nwindow.W3Assets = ${JSON.stringify(assets)};\n`);
await mkdir(resolve(here, 'licenses'), { recursive: true });
await copyFile(resolve(root, 'website/src/icons/LICENSE'), resolve(here, 'licenses/PHOSPHOR.txt'));
await copyFile(resolve(root, 'website/public/fonts/OFL-barlow-condensed.txt'), resolve(here, 'licenses/BARLOW-CONDENSED.txt'));
await copyFile(resolve(root, 'website/public/fonts/OFL-onest.txt'), resolve(here, 'licenses/ONEST.txt'));
console.log('Bundled the current website rook/CHESS lockup, 5 sculptures, 15 Phosphor icons and 2 licensed fonts.');
